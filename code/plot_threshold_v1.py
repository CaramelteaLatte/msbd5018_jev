#!/usr/bin/env python3
"""Redraw the v1 README figure from saved results, without model API calls.

The original step plot was generated by write_plot() in run_threshold.py
at commit 02478e5. That script now runs v2; this entry point keeps v1
plotting separate and does not recompute or change the selected threshold.
"""

import argparse
import csv
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
SERIES = (
    ("qwen3.8-max_accuracy", "JEV + Qwen", "#1f77b4", "o"),
    ("deepseek-v4.1-flash-1017_accuracy", "JEV + DeepSeek", "#ff7f0e", "s"),
    ("kimi-k3.1-pro_accuracy", "JEV + Kimi", "#2ca02c", "^"),
    ("mean_cascade_accuracy", "Mean across three cascades", "#18181b", "x"),
)


def plot_thresholds(rows, report):
    # The empty threshold is "never route", not a confidence value of zero.
    numeric = sorted((r for r in rows if r["confidence_threshold"] != ""),
                     key=lambda r: float(r["confidence_threshold"]))
    x = [float(r["confidence_threshold"]) for r in numeric]
    if len(x) != len(set(x)):
        raise ValueError("Expected one saved row per distinct confidence threshold")
    n = report["validation_size"]
    baseline = report["baseline_jev_accuracy"]
    selected = report["selected"]
    cutoff = selected["confidence_threshold"]
    budget = 100 * report["max_routing_rate"]

    fig, (accuracy, routing) = plt.subplots(
        2, 1, figsize=(11, 7.5), sharex=True, height_ratios=[3, 1], layout="constrained",
    )
    fig.suptitle(f"VitaminC v1 | discrete confidence thresholds | validation n={n:,}")
    accuracy.axhline(100 * baseline, color="#52525b", linestyle="--",
                     linewidth=1.2, label=f"JEV only ({baseline:.2%})")
    for column, label, color, marker in SERIES:
        y = [100 * float(r[column]) for r in numeric]
        accuracy.scatter(x, y,
                         s=32, marker=marker, color=color, alpha=.85, label=label,
                         zorder=3 if marker == "x" else 2)
    routing.scatter(x, [100 * float(r["routing_rate"]) for r in numeric],
                    s=26, color="#0f766e", zorder=2)
    if not numeric:
        accuracy.set_xlim(0, 1)
        accuracy.text(.5, .5, "No confidence group fits the routing budget",
                      ha="center", transform=accuracy.transAxes)
    if cutoff is not None:
        for axis in (accuracy, routing):
            axis.axvline(cutoff, color="#be123c", linewidth=1, linestyle=":")
        accuracy.scatter([cutoff], [100 * selected["mean_cascade_accuracy"]],
                         s=115, facecolors="none", edgecolors="#be123c", linewidths=1.5,
                         label="Selected mean", zorder=4)
        accuracy.set_title(
            f"Selected: confidence <= {cutoff:g} | routed {selected['routed']}/{n} "
            f"({selected['routing_rate']:.2%})", loc="left", fontsize=10,
        )
    else:
        accuracy.set_title("Selected: JEV only (zero LLM calls)", loc="left", fontsize=10)
    accuracy.set_ylabel("Cascade accuracy over all validation samples (%)")
    accuracy.legend(loc="best", fontsize=8, ncols=2)
    routing.axhline(budget, color="#52525b", linestyle="--", linewidth=1,
                    label=f"Routing budget ({budget:g}%)")
    routing.set_ylim(0, max(1, budget * 1.12))
    routing.set_ylabel("Routed (%)")
    routing.set_xlabel("Raw JEV confidence cutoff (route if confidence <= cutoff)")
    routing.legend(loc="upper left", fontsize=8)
    for axis in (accuracy, routing):
        axis.grid(axis="y", alpha=.2)
        axis.set_axisbelow(True)
    return fig


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sweep", type=Path, default=ROOT / "code/threshold_results/threshold_sweep.csv")
    parser.add_argument("--selection", type=Path, default=ROOT / "code/threshold_results/selected_threshold.json")
    parser.add_argument("--out", type=Path, default=ROOT / "assets/threshold_curve.png")
    args = parser.parse_args()
    with args.sweep.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    report = json.loads(args.selection.read_text(encoding="utf-8"))
    fig = plot_thresholds(rows, report)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(args.out, dpi=180)
    plt.close(fig)
    print(f"Saved v1 scatter plot: {args.out}")


if __name__ == "__main__":
    main()
